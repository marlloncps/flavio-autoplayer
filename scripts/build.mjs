import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const planner = await readFile(new URL('src/planner.js', root), 'utf8');
const overlay = await readFile(new URL('src/overlay.js', root), 'utf8');
const speed = await readFile(new URL('src/speed.js', root), 'utf8');
const weapon = await readFile(new URL('src/weapon.js', root), 'utf8');
const weaponView = await readFile(new URL('src/weapon-view.js', root), 'utf8');
const controller = await readFile(new URL('src/controller.js', root), 'utf8');
const bundle = `/* Flávio Autoplayer 0.5.0 — local, sem serviços externos */\n(()=>{\n'use strict';\n${planner.replaceAll('export function ', 'function ')}\n${overlay.replaceAll('export function ', 'function ')}\n${speed.replaceAll('export function ', 'function ')}\n${weapon.replaceAll('export function ', 'function ')}\n${weaponView.replaceAll('export function ', 'function ')}\n${controller.replace(/^import .*\n/gm, '').replaceAll('export function ', 'function ')}\ninstallBot(window,document);\n})();\n`;
await writeFile(new URL('extension/bot.js', root), bundle);
console.log('Extensão criada em extension/');
